(* Why3 goal *)
Theorem wp_goal :
  forall (i:Numbers.BinNums.Z),
  let x := lsr (land 16711680%Z i) 8%Z in
  let x1 := lsr (land 4278190080%Z i) 24%Z in
  let x2 := lsl (land 255%Z i) 24%Z in
  let x3 := lsl (land 65280%Z i) 8%Z in
  is_uint32 i -> is_uint32 x -> is_uint32 x1 ->
  ((lor x (lor x1 (lor (to_uint32 x2) (to_uint32 x3)))) =
   (lor x2 (lor x3 (lor x x1)))).
Proof.
intros i x x1 x2 x3 h1 h2 h3.
Require Import ZArith Lia.
(* WP's integer and bit theory, related to Coq's: every lemma below is
   derived from the axioms above, and the goal is then proved with Coq's
   ZArith. *)
assert (P2 : forall n, (0 <= n)%Z -> two_power_abs n = (2 ^ n)%Z).
{ apply natlike_ind.
  - rewrite <- lsl_1_two_power by lia. rewrite lsl_1_0. reflexivity.
  - intros m Hm IH. unfold Z.succ. rewrite two_power_abs_plus_one by lia.
    rewrite IH, Z.pow_add_r, Z.pow_1_r by lia. ring. }
assert (LSL : forall a n, (0 <= n)%Z -> lsl a n = (a * 2 ^ n)%Z).
{ intro a. apply natlike_ind.
  - rewrite lsl_0, Z.pow_0_r. ring.
  - intros m Hm IH. unfold Z.succ. rewrite <- (lsl_add a m 1) by lia.
    rewrite lsl_1, IH, Z.pow_add_r, Z.pow_1_r by lia. ring. }
assert (LSRpos : forall a n, (0 <= a)%Z -> (0 <= n)%Z -> lsr a n = (a / 2 ^ n)%Z).
{ intros a n Ha. revert n. apply natlike_ind.
  - rewrite lsr_0, Z.pow_0_r, Z.div_1_r. reflexivity.
  - intros m Hm IH. unfold Z.succ. rewrite <- (lsr_add a m 1) by lia.
    assert (Hq : (0 <= a / 2 ^ m)%Z)
      by (apply Z.div_pos; [lia | apply Z.pow_pos_nonneg; lia]).
    rewrite lsr_1 by (rewrite IH; exact Hq).
    rewrite IH, Z.quot_div_nonneg by lia.
    rewrite Z.div_div by (try apply Z.pow_nonzero; lia).
    rewrite Z.pow_add_r, Z.pow_1_r by lia. reflexivity. }
assert (B0 : forall a, bit_test a 0 <-> Z.testbit a 0 = true).
{ intro a. destruct (Z.Even_or_Odd a) as [[q Hq] | [q Hq]]; subst a.
  - rewrite Z.testbit_even_0. split; [ | discriminate]. intro H. exfalso.
    apply (lsl_extraction_inf q 1 0); try lia. rewrite lsl_1. exact H.
  - rewrite Z.testbit_odd_0. split; [reflexivity | intros _].
    assert (H1 : land (2 * q) 1 = 0%Z).
    { assert (Hr : (0 <= land (2 * q) 1 < lsl 1 0)%Z).
      { apply pos_extraction_sup_inv; [lia | ]. intros j Hj Hb.
        apply land_extraction in Hb; [ | lia]. destruct Hb as [Hb1 Hb2].
        destruct (Z.eq_dec j 0) as [Hj0 | Hj0].
        - subst j. apply (lsl_extraction_inf q 1 0); try lia.
          rewrite lsl_1. exact Hb1.
        - rewrite <- lsl_1_0 in Hb2. apply lsl1_extraction in Hb2; lia. }
      rewrite lsl_1_0 in Hr. lia. }
    rewrite (lor_addition (2 * q) 1 H1). apply lor_extraction; [lia | ].
    right. rewrite <- lsl_1_0. apply lsl1_extraction; lia. }
assert (BTpos : forall a k, (0 <= a)%Z -> (0 <= k)%Z ->
                 (bit_test a k <-> Z.testbit a k = true)).
{ intros a k Ha Hk.
  rewrite <- (Z.add_0_l k) at 1.
  rewrite <- (lsr_extractionl a k 0 Hk (Z.le_refl 0)).
  rewrite B0, LSRpos, <- Z.shiftr_div_pow2, Z.shiftr_spec, Z.add_0_l by lia.
  reflexivity. }
assert (BT : forall a k, (0 <= k)%Z -> (bit_test a k <-> Z.testbit a k = true)).
{ intros a k Hk. destruct (Z.le_gt_cases 0 a) as [Ha | Ha].
  - apply BTpos; assumption.
  - replace a with (lnot (- a - 1)) by (unfold lnot; ring).
    rewrite lnot_extraction, BTpos by lia.
    replace (lnot (- a - 1)) with (Z.lnot (- a - 1)) by (unfold lnot, Z.lnot; lia).
    rewrite Z.lnot_spec by lia.
    destruct (Z.testbit (- a - 1) k); simpl; intuition congruence. }
assert (EXT : forall a b, (forall k, (0 <= k)%Z -> (bit_test a k <-> bit_test b k)) -> a = b).
{ intros a b H.
  assert (Hp := Z.pow_gt_lin_r 2 (Z.abs a + Z.abs b + 1) ltac:(lia) ltac:(lia)).
  apply (is_sint_ext (Z.abs a + Z.abs b + 1) a b).
  - lia.
  - unfold is_sint. rewrite P2 by lia. lia.
  - unfold is_sint. rewrite P2 by lia. lia.
  - intros k [Hk _]. apply H. exact Hk. }
assert (LAND : forall a b, land a b = Z.land a b).
{ intros a b. apply EXT. intros k Hk.
  rewrite land_extraction, !BT, Z.land_spec, Bool.andb_true_iff by exact Hk.
  reflexivity. }
assert (LOR : forall a b, lor a b = Z.lor a b).
{ intros a b. apply EXT. intros k Hk.
  rewrite lor_extraction, !BT, Z.lor_spec, Bool.orb_true_iff by exact Hk.
  reflexivity. }
assert (LXOR : forall a b, lxor a b = Z.lxor a b).
{ intros a b. apply EXT. intros k Hk.
  rewrite lxor_extraction, !BT, Z.lxor_spec by exact Hk.
  destruct (Z.testbit a k), (Z.testbit b k); simpl; intuition congruence. }
assert (LSR : forall a n, (0 <= n)%Z -> lsr a n = Z.shiftr a n).
{ intros a n Hn. apply EXT. intros k Hk.
  rewrite lsr_extractionl, !BT, Z.shiftr_spec by lia. reflexivity. }
assert (U64 : forall a, to_uint64 a = (a mod 2 ^ 64)%Z).
{ intro a. apply EXT. intros k Hk. destruct (Z.lt_ge_cases k 64) as [Hlt | Hge].
  - rewrite to_uint64_extraction_inf, !BT, Z.mod_pow2_bits_low by lia. reflexivity.
  - split; intro H.
    + exfalso. exact (to_uint64_extraction_sup (to_uint64 a) k Hge (is_to_uint64 a) H).
    + apply BT in H; [ | lia]. rewrite Z.mod_pow2_bits_high in H by lia. discriminate. }
assert (U32 : forall a, to_uint32 a = (a mod 2 ^ 32)%Z).
{ intro a. apply EXT. intros k Hk. destruct (Z.lt_ge_cases k 32) as [Hlt | Hge].
  - rewrite to_uint32_extraction_inf, !BT, Z.mod_pow2_bits_low by lia. reflexivity.
  - split; intro H.
    + exfalso. exact (to_uint32_extraction_sup (to_uint32 a) k Hge (is_to_uint32 a) H).
    + apply BT in H; [ | lia]. rewrite Z.mod_pow2_bits_high in H by lia. discriminate. }
assert (LNOT : forall a, lnot a = Z.lnot a) by (intro a; unfold lnot, Z.lnot; lia).
assert (HI : forall a n, (0 <= a < 2 ^ 64)%Z -> (64 <= n)%Z -> Z.testbit a n = false).
{ intros a n Ha Hn. rewrite <- (Z.mod_small a (2 ^ 64)) by lia.
  apply Z.mod_pow2_bits_high. lia. }
Require Import Btauto.
(* Each shifted byte is below 2^32, so the casts change nothing, and both
   sides OR the same four terms. *)
assert (E2 : to_uint32 x2 = x2).
{ apply id_uint32. unfold x2, is_uint32.
  pose proof (uint_land_range 255 i ltac:(lia)). rewrite LSL by lia. lia. }
assert (E3 : to_uint32 x3 = x3).
{ apply id_uint32. unfold x3, is_uint32.
  pose proof (uint_land_range 65280 i ltac:(lia)). rewrite LSL by lia. lia. }
rewrite E2, E3, !LOR. apply Z.bits_inj'. intros n Hn.
rewrite !Z.lor_spec. btauto.
Qed.

